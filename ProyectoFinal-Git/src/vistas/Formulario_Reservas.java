    public Formulario_Reservas(ListadoReservas pParent, boolean modal, String pMode, int pId) {
        super(pParent, modal);
        this.parent = pParent;
        initComponents();
        cargarCombos();
        
        dao = new ReservasDAO();
        this.mode = pMode;
        this.id = pId;
        jTextField6.setText(String.valueOf(pId));
        
        if(mode.equals("INS")){
            jButton1.setText("GUARDAR");
            jTextField6.setText(String.valueOf(dao.SiguienteID()));
            jTextField6.setEditable(false);
        }else if(mode.equals("UPD")){
            ReservasModel Reserva = (ReservasModel) dao.getById(id);
            jTextField1.setText(Reserva.getTiempo());
            jTextField2.setText(String.valueOf(Reserva.getTipoPago()));
            jTextField3.setText(Reserva.getEstado());
            jButton1.setText("GUARDAR");
        }else if(mode.equals("DLT")){
            ReservasModel Reserva = (ReservasModel) dao.getById(id);
            jTextField1.setText(Reserva.getTiempo());
            jTextField2.setText(String.valueOf(Reserva.getTipoPago()));
            jTextField3.setText(Reserva.getEstado());
            jTextField1.setEnabled(false);
            jTextField2.setEnabled(false);
            jTextField3.setEnabled(false);
            jComboBox2.setEnabled(false);
            jComboBox3.setEnabled(false);
            jButton1.setText("ELIMINAR");
        }
   }
    
    private void cargarCombos() {
    // Cargar huéspedes
    List<Integer> huespedes = ReservasDAO.obtenerIDHuesped();
    for (Integer h : huespedes) {
        jComboBox2.addItem(h.toString());
    }

    // Cargar habitaciones
    List<Integer> habitaciones = ReservasDAO.obtenerIdHabitacion();
    for (Integer h : habitaciones) {
        jComboBox3.addItem(h.toString());
    }
}

