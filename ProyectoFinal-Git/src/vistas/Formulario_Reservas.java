    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if(mode.equals("INS")){
            ReservasModel Reserva = new ReservasModel();
            Reserva.setIDReserva(Integer.parseInt(jTextField6.getText()));
            Reserva.setIDHuesped(Integer.parseInt(jComboBox2.getSelectedItem().toString()));
            Reserva.setIDHabitacion(Integer.parseInt(jComboBox3.getSelectedItem().toString()));
            Reserva.setTiempo(jTextField1.getText());
            Reserva.setTipoPago(Integer.parseInt(jTextField2.getText()));
            Reserva.setEstado(jTextField3.getText());
            dao.insert(Reserva);
            parent.Refresh();
            this.dispose();
        }
        if(mode.equals("UPD")){
            ReservasModel Reserva = new ReservasModel();
            Reserva.setIDHuesped(Integer.parseInt(jComboBox2.getSelectedItem().toString()));
            Reserva.setIDHabitacion(Integer.parseInt(jComboBox3.getSelectedItem().toString()));
            Reserva.setTiempo(jTextField1.getText());
            Reserva.setTipoPago(Integer.parseInt(jTextField2.getText()));
            Reserva.setEstado(jTextField3.getText());
            Reserva.setIDReserva(id);
            dao.update(Reserva);
            parent.Refresh();
            this.dispose();
        }
        if(mode.equals("DLT")){           
            dao.delete(id);
            parent.Refresh();
            this.dispose();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

